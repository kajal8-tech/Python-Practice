# Arithmetic Operators
a = 34
b = 4
c = a+b
print(c)

#Assignment Operators
d = 4-2 # Assign 4-2 in a
print(d)

e = 6 
e += 3 # Increment the value of 'e' by 3 then assign it to 'e'
e -= 3 # Decrement the value of 'e' by 3 then assign it to 'e'
e *= 3 # Multiple the value of 'e' by 3 then assign it to 'e'
e /= 3 # Divide the value of 'e' by 3 then assign it to 'e'
print(e)

# Comparison Operators

f = 5<4
print(f)

